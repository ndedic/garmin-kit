// Regenerates the tool list (write-capable tools such as download are deliberately left out of the model-facing skill) in skills/garmin/SKILL.md from the core tool registry.
// Usage: npm run gen:skill   (add --check to fail if the file is out of date)
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { flagName, tools } from "../packages/core/src/tools.js";

const file = resolve(import.meta.dirname, "../skills/garmin/SKILL.md");
const START = "<!-- tools:start (generated by `npm run gen:skill`; edit packages/core/src/tools.ts) -->";
const END = "<!-- tools:end -->";

const block = tools.filter((t) => t.surfaces.includes("cli") && !t.writes).map((t) => {
  const args = t.params.map((p) => (p.positional ? (p.required ? "ACTIVITY_ID" : "[ACTIVITY_ID]") : `[${flagName(p)} ${p.enum ? p.enum.join("|") : p.type === "integer" ? "N" : "VALUE"}]`));
  return `- \`garmin ${[t.cli, ...args].join(" ")}\` — ${t.description}`;
}).join("\n") + "\n- `garmin last-run` — shorthand for `garmin runs --limit 1`.";

const current = readFileSync(file, "utf8");
const pattern = new RegExp(`${START.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}[\\s\\S]*?${END}`);
const replacement = `${START}\n${block}\n${END}`;
if (!pattern.test(current)) throw new Error("Markers not found in SKILL.md");
const next = current.replace(pattern, () => replacement);
if (process.argv.includes("--check")) {
  if (next !== current) { console.error("skills/garmin/SKILL.md is out of date; run npm run gen:skill"); process.exit(1); }
} else writeFileSync(file, next);
